"""Generate Goonmoji's data files and icons from tools/cache (see fetch_sources.py).

    python3 -P tools/build.py

Writes
  Data/CodePoints.lua   emoji code point detector (full Unicode set, never pruned)
  Data/Emojis.lua       standard emoji metadata (curated by noto_rules.py)
  Data/NotoPack.lua     Noto icon pack
  Data/SAPack.lua       SomethingAwful sticker pack (curated by sa_manifest.txt)
  Icons/Noto/*.png      64x64
  Icons/SA/*.png        power-of-two canvases / flipbook sheets
  tools/out/noto_pruned.txt, tools/out/build_report.txt
"""
