# ----------------------------------------------------------------------------- helpers

def lua_str(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "")
    return f'"{s}"'


def lua_list(items, indent):
    pad = "\t" * indent
    return "".join(f"{pad}{lua_str(i)},\n" for i in items)


def key_of(cps):
    return "_".join(str(c) for c in cps)


def slug(text):
    s = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    return s or "x"


def next_pow2(n):
    return 1 << max(0, math.ceil(math.log2(max(1, n))))


# ----------------------------------------------------------------------------- emoji-test

def parse_emoji_test():
    group = subgroup = None
    rows = []
    line_re = re.compile(r"^([0-9A-F ]+?)\s*;\s*([\w-]+)\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.+)$")
    for line in open(os.path.join(CACHE, "emoji-test.txt"), encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
        elif line.startswith("# subgroup:"):
            subgroup = line.split(":", 1)[1].strip()
        elif line and not line.startswith("#"):
            m = line_re.match(line)
            if not m:
                continue
            rows.append({
                "cps": R.parse(m.group(1)), "status": m.group(2), "char": m.group(3),
                "since": m.group(4), "name": m.group(5), "group": group, "subgroup": subgroup,
            })
    return rows


# ----------------------------------------------------------------------------- code points

def build_codepoints(rows):
    special = {0xFE0F, 0x200D, 0x20E3, 0xE007F} | R.SKIN_TONES | set(range(0x1F9B0, 0x1F9B3)) \
        | set(range(0x1F1E6, 0x1F200))
    cps = sorted({c for r in rows for c in r["cps"] if c >= 0x80 and c not in special})
    body = []
    line = "\t"
    for c in cps:
        item = f"[0x{c:X}]=true, "
        if len(line) + len(item) > 100:
            body.append(line.rstrip())
            line = "\t"
        line += item
    body.append(line.rstrip())
    with open(os.path.join(DATA, "CodePoints.lua"), "w", encoding="utf-8") as f:
        f.write(f"""-- Generated by tools/build.py from Unicode emoji-test.txt. Do not edit.
local _, addon = ...

-- Every code point that can start or appear inside an RGI emoji sequence,
-- excluding ASCII and the sequence components handled explicitly below.
local EMOJI_CODEPOINTS = {{
{chr(10).join(body)}
}}

-- check code point is emoji code point
-- return:
-- params1: isEmojiCodePoint: boolean
-- params2: before: number: how many codepoint before this codepoint maybe emoji, maybe nil
-- params3: after: number: how many codepoint after this codepoint maybe emoji, maybe nil
-- params4: combineFlag: string
function addon:CodePointIsEmoji(codePoint)
	if codePoint < 0x80 then
		-- 0-9 # * only form emoji as part of a keycap sequence (handled by 0xFE0F / 0x20E3)
		return false
	elseif codePoint == 0xFE0F or codePoint == 0x20E3 then
		-- variation selector-16, combining keycap
		return true, 1, 0
	elseif codePoint == 0x200D then
		-- zero width joiner
		return true, 1, 1
	elseif (codePoint >= 0x1F3FB and codePoint <= 0x1F3FF) or (codePoint >= 0x1F9B0 and codePoint <= 0x1F9B2) then
		-- skin tone, hair style
		return true, 1, 0
	elseif codePoint == 0xE007F then
		-- cancel tag: England, Scotland, Wales
		return true, 6, 0
	elseif codePoint >= 0x1F1E6 and codePoint <= 0x1F1FF then
		-- regional indicator: pairs combine into a country flag
		return false, 1, 0, "country flag"
	end
	return EMOJI_CODEPOINTS[codePoint] == true
end
""")
    return len(cps)


# ----------------------------------------------------------------------------- noto

def noto_file(cps):
    return "emoji_u" + "_".join(f"{c:04x}" for c in R.strip_vs(cps)) + ".png"


_flag_font = None


def render_flag(char):
    """Country flags only ship inside the flags-only colour font; render one to RGBA."""
    global _flag_font
    if _flag_font is None:
        _flag_font = ImageFont.truetype(FLAG_FONT, 109)  # CBDT strikes are 109px
    im = Image.new("RGBA", (160, 160), (0, 0, 0, 0))
    ImageDraw.Draw(im).text((0, 0), char, font=_flag_font, embedded_color=True)
    box = im.getbbox()
    if not box:
        return None
    im = im.crop(box)
    im.thumbnail((NOTO_SIZE, NOTO_SIZE), Image.LANCZOS)
    canvas = Image.new("RGBA", (NOTO_SIZE, NOTO_SIZE), (0, 0, 0, 0))
    canvas.paste(im, ((NOTO_SIZE - im.width) // 2, (NOTO_SIZE - im.height) // 2))
    return canvas


def build_noto(rows, legacy, sa_codes):
    src_dir = os.path.join(CACHE, "noto", NOTO_STYLE, "png", "72")
    available = set(os.listdir(src_dir))
    flag_art = {}
    for r in rows:
        if r["status"] == "fully-qualified" and r["subgroup"] == "country-flag" \
                and noto_file(r["cps"]) not in available:
            art = render_flag(r["char"])
            if art:
                flag_art[noto_file(r["cps"])] = art
    # England/Scotland/Wales: no glyph in the flags font either; use the flat region flags.
    for r in rows:
        if r["status"] == "fully-qualified" and r["subgroup"] == "subdivision-flag" \
                and noto_file(r["cps"]) not in available:
            region = "GB-" + "".join(chr(c - 0xE0000) for c in r["cps"][3:-1]).upper()
            path = os.path.join(CACHE, "noto", "third_party", "region-flags", "png", region + ".png")
            if os.path.exists(path):
                with Image.open(path) as im:
                    im = im.convert("RGBA")
                    im.thumbnail((NOTO_SIZE - 8, NOTO_SIZE - 8), Image.LANCZOS)
                    canvas = Image.new("RGBA", (NOTO_SIZE, NOTO_SIZE), (0, 0, 0, 0))
                    canvas.paste(im, ((NOTO_SIZE - im.width) // 2, (NOTO_SIZE - im.height) // 2))
                    flag_art[noto_file(r["cps"])] = canvas
    available |= set(flag_art)
    fq_rows = [r for r in rows if r["status"] == "fully-qualified"]
    fq = {r["cps"] for r in fq_rows}
    by_cps = {r["cps"]: r for r in fq_rows}

    # 1. bucket every fully-qualified emoji
    decision = {}
    for r in fq_rows:
        bucket, target = R.classify(r["cps"], r["group"], r["subgroup"], fq)
        if bucket in ("KEEP", "HIDDEN") and noto_file(r["cps"]) not in available:
            # No artwork: fall back to an alias if a base exists, else drop.
            target = next((c for c in R.base_candidates(r["cps"]) if c in fq and c != r["cps"]), None)
            bucket = "ALIAS" if target else "DROP"
        decision[r["cps"]] = [bucket, target]

    # 2. resolve alias chains to a KEEP/HIDDEN target
    def resolve(cps, depth=0):
        bucket, target = decision.get(cps, ["DROP", None])
        if bucket != "ALIAS":
            return cps if bucket in ("KEEP", "HIDDEN") else None
        if depth > 8 or target is None:
            return None
        return resolve(target, depth + 1)

    canonical = {}      # key -> canonical key (for every alias / variant)
    for r in rows:
        if r["status"] == "component":
            continue
        cps = r["cps"]
        if r["status"] != "fully-qualified":
            # minimally-qualified / unqualified -> its fully-qualified form
            fq_match = next((f for f in fq if R.strip_vs(f) == R.strip_vs(cps)), None)
            if not fq_match:
                continue
            cps_fq = fq_match
        else:
            cps_fq = cps
        target = resolve(cps_fq)
        if target is None:
            continue
        if cps != target:
            canonical[key_of(cps)] = key_of(target)
        # Some clients append VS16 to emoji that don't need it ("ADDON_COMPAT" upstream).
        if cps[-1] != R.VS16 and len(R.strip_vs(cps)) == 1:
            canonical.setdefault(key_of(cps + (R.VS16,)), key_of(target))

    shipped = [r for r in fq_rows if decision[r["cps"]][0] in ("KEEP", "HIDDEN")]
    kept = [r for r in shipped if decision[r["cps"]][0] == "KEEP"]
    canonical = {k: v for k, v in canonical.items() if k not in {key_of(r["cps"]) for r in shipped}}

    # 3. names / keywords / shortcodes
    ann = json.load(open(os.path.join(CACHE, "cldr-annotations.json"), encoding="utf-8"))["annotations"]["annotations"]
    ann_d = json.load(open(os.path.join(CACHE, "cldr-annotations-derived.json"), encoding="utf-8"))["annotationsDerived"]["annotations"]
    gh = {k.upper(): v for k, v in json.load(open(os.path.join(CACHE, "emojibase-github.json"), encoding="utf-8")).items()}
    eb_cldr = {k.upper(): v for k, v in json.load(open(os.path.join(CACHE, "emojibase-cldr.json"), encoding="utf-8")).items()}

    def annotations(r):
        for table in (ann, ann_d):
            for ch in (r["char"], r["char"].replace("\ufe0f", "")):
                if ch in table:
                    return table[ch].get("default", [])
        return []

    def as_list(v):
        return v if isinstance(v, list) else [v]

    used = set(sa_codes)     # SA wins: Noto never claims an SA code
    meta = OrderedDict()
    removed_for_sa = []
    for r in shipped:
        key = key_of(r["cps"])
        hexkey = "-".join(f"{c:04X}" for c in R.strip_vs(r["cps"]))
        candidates = list(legacy["shortcodes"].get(key, []))
        if not candidates:
            candidates = as_list(gh.get(hexkey, [])) + as_list(eb_cldr.get(hexkey, []))
        candidates.append(slug(r["name"]))
        shortcodes = []
        for sc in candidates:
            if sc in sa_codes:
                if (sc, r["char"]) not in removed_for_sa:
                    removed_for_sa.append((sc, r["char"]))
                continue
            if sc not in used and sc not in shortcodes:
                shortcodes.append(sc)
        if not shortcodes:
            fallback = slug(r["name"]) + "_emoji"
            shortcodes.append(fallback)
        used.update(shortcodes)
        words = []
        for w in [r["name"]] + annotations(r):
            w = w.strip()
            if w and w.lower() not in (x.lower() for x in words):
                words.append(w)
        meta[key] = {"name": r["name"], "shortcodes": shortcodes, "keywords": words[1:], "row": r}

    # 4. icons
    shutil.rmtree(ICONS_NOTO, ignore_errors=True)
    os.makedirs(ICONS_NOTO)
    icons = OrderedDict()
    for r in shipped:
        fname = noto_file(r["cps"])[len("emoji_u"):]
        if noto_file(r["cps"]) in flag_art:
            flag_art[noto_file(r["cps"])].save(os.path.join(ICONS_NOTO, fname), optimize=True)
        else:
            with Image.open(os.path.join(src_dir, noto_file(r["cps"]))) as im:
                im.convert("RGBA").resize((NOTO_SIZE, NOTO_SIZE), Image.LANCZOS).save(
                    os.path.join(ICONS_NOTO, fname), optimize=True)
        icons[key_of(r["cps"])] = fname

    # 5. groups (keyboard): only KEEP emoji
    groups = OrderedDict()
    for r in kept:
        groups.setdefault(r["group"], OrderedDict()).setdefault(r["subgroup"], []).append(key_of(r["cps"]))

    popular = []
    for k in legacy["popular"]:
        k = canonical.get(k, k)
        if k in meta and k not in popular and decision[R.parse(" ".join(f"{int(x):X}" for x in k.split("_")))][0] == "KEEP":
            popular.append(k)

    write_emojis_lua(meta, groups, popular, canonical, legacy, kept)
    write_noto_pack_lua(icons, canonical)

    with open(os.path.join(OUT, "noto_pruned.txt"), "w", encoding="utf-8") as f:
        for r in fq_rows:
            bucket, target = decision[r["cps"]]
            res = resolve(r["cps"])
            arrow = f" -> {by_cps[res]['char']} {by_cps[res]['name']}" if bucket == "ALIAS" and res else ""
            f.write(f"{bucket:6} {r['char']}\t{r['group']} / {r['subgroup']}\t{r['name']}{arrow}\n")

    counts = {b: sum(1 for d in decision.values() if d[0] == b) for b in ("KEEP", "HIDDEN", "ALIAS", "DROP")}
    return counts, len(icons), len(canonical), removed_for_sa


def write_emojis_lua(meta, groups, popular, canonical, legacy, kept):
    out = []
    w = out.append
    w("-- Generated by tools/build.py (Unicode emoji-test + CLDR + Emoji-Core shortcodes). Do not edit.\n")
    w("local addonName, addon = ...\n\nlocal E = {\n")
    w(f"\tPopular = {{\n\t\tName = \"Popular\",\n\t\tEmojiCount = {len(popular)},\n")
    w(lua_list(popular, 2))
    w("\t},\n\n")

    total = sum(len(v) for sub in groups.values() for v in sub.values())
    w(f"\tGroupInfo = {{\n\t\tGroupCount = {len(groups)},\n\t\tEmojiCount = {total},\n")
    for gname, subs in groups.items():
        first = next(iter(subs.values()))[0]
        gcount = sum(len(v) for v in subs.values())
        disp = legacy["group_names"].get(gname, gname)
        w(f"\t\t{{\n\t\t\tName = {lua_str(disp)},\n\t\t\tIconKey = {lua_str(first)},\n"
          f"\t\t\tSubGroupCount = {len(subs)},\n\t\t\tEmojiCount = {gcount},\n")
        for sname, keys in subs.items():
            sdisp = legacy["subgroup_names"].get(sname, sname.replace("-", " ").title())
            w(f"\t\t\t{{\n\t\t\t\tName = {lua_str(sdisp)},\n\t\t\t\tEmojiCount = {len(keys)},\n")
            w(lua_list(keys, 4))
            w("\t\t\t},\n")
        w("\t\t},\n")
    w("\t},\n\n")

    kept_keys = {key_of(r["cps"]) for r in kept}
    shortcode_list = []
    w("\tShortcodesToKey = {\n")
    for key, m in meta.items():
        for sc in m["shortcodes"]:
            w(f"\t\t[{lua_str(sc)}] = {lua_str(key)},\n")
            if key in kept_keys:
                shortcode_list.append(sc)
    w("\t},\n\n")
    w("\tShortcodeList = {\n")
    w(lua_list(shortcode_list, 2))
    w(f"\t\tShortcodeCount = {len(shortcode_list)},\n\t}},\n\n")

    kw_index = OrderedDict()
    for key, m in meta.items():
        if key not in kept_keys:
            continue
        for kw in m["keywords"]:
            kw = kw.lower()
            lst = kw_index.setdefault(kw, [])
            if key not in lst:
                lst.append(key)
    w("\tKeywordList = {\n")
    w(lua_list(list(kw_index), 2))
    w(f"\t\tKeywordCount = {len(kw_index)},\n")
    w("\t},\n\tKeywordIndexes = {\n")
    for kw, keys in kw_index.items():
        w(f"\t\t[{lua_str(kw)}] = {{ {', '.join(lua_str(k) for k in keys)} }},\n")
    w("\t},\n\n")

    w("\t-- enable auto complete shortcode without a start delimiter if text len with [min, max] range\n"
      "\tAutoCompleteMinLength = 2,\n\tAutoCompleteMaxLength = 9,\n\n"
      "\t-- ·: 0xB7\n\tStickerDelimiterCodePoint = 183,\n"
      "\t-- :: 0x3A\n\tShortcodeStartCodePoint = 58,\n\tShortcodeCompleteCodePoint = 58,\n"
      "\tShortcodeStartDelimiter = \":\",\n\tShortcodeEndDelimiter = \":\",\n\n")

    for key, m in meta.items():
        r = m["row"]
        w(f"\t-- {r['char']} E{r['since']}\n")
        w(f"\t[{lua_str(key)}] = {{\n\t\tName = {lua_str(m['name'])},\n")
        w(f"\t\tShortcodes = {{ {', '.join(lua_str(s) for s in m['shortcodes'])} }},\n")
        if m["keywords"]:
            w(f"\t\tKeywords = {{ {', '.join(lua_str(k) for k in m['keywords'])} }},\n")
        w("\t},\n")
    w("}\n\n")

    w("-- Variant sequences (unqualified, skin tones, gendered, ...) render as their base emoji.\n")
    w("local aliases = {\n")
    for alias, key in sorted(canonical.items()):
        w(f"\t[{lua_str(alias)}] = {lua_str(key)},\n")
    w("}\nfor alias, key in pairs(aliases) do\n\tE[alias] = E[key]\nend\n")
    w("E.Aliases = aliases\n\naddon.Emojis = E\n")

    with open(os.path.join(DATA, "Emojis.lua"), "w", encoding="utf-8") as f:
        f.write("".join(out))


def write_noto_pack_lua(icons, canonical):
    out = ["-- Generated by tools/build.py from googlefonts/noto-emoji. Do not edit.\n",
           "local addonName, addon = ...\n\n",
           "local icons = {\n"]
    for key, fname in icons.items():
        out.append(f"\t[{lua_str(key)}] = {lua_str(fname)},\n")
    out.append("}\n")
    out.append("for alias, key in pairs(addon.Emojis.Aliases) do\n\ticons[alias] = icons[key]\nend\n\n")
    out.append(f"""addon:RegisterEmojiPack({{
	ID = "GoogleNoto",
	Name = "Noto Emoji",
	IconDir = "{ADDON_PATH}Noto\\\\",
	Icons = icons,
}})
""")
    with open(os.path.join(DATA, "NotoPack.lua"), "w", encoding="utf-8") as f:
        f.write("".join(out))


# ----------------------------------------------------------------------------- SA

def parse_sa_manifest():
    path = os.path.join(TOOLS, "sa_manifest.txt")
    entries = []
    category = "Something Awful"
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("## "):
            category = line[3:].strip()
            continue
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 2:
            print(f"  manifest: ignoring malformed line: {line!r}")
            continue
        entries.append({"code": parts[0].strip(), "file": parts[1].strip(), "category": category})
    return entries


def sa_shortcode(code):
    """':v:' -> 'v' ; ':)' -> None (bare emoticon)"""
    m = re.fullmatch(r":([^:\s]+):", code)
    return m.group(1) if m else None


def load_frames(path):
    with Image.open(path) as im:
        frames, durations = [], []
        for frame in ImageSequence.Iterator(im):
            frames.append(frame.convert("RGBA"))
            d = frame.info.get("duration", 100) or 100
            durations.append(100 if d <= 10 else max(d, SA_MIN_FRAME_MS))
    return frames, durations


def decimate(frames, durations):
    n = len(frames)
    if n <= SA_MAX_FRAMES:
        return frames, durations
    out_f, out_d = [], []
    for i in range(SA_MAX_FRAMES):
        a = i * n // SA_MAX_FRAMES
        b = (i + 1) * n // SA_MAX_FRAMES
        out_f.append(frames[a])
        out_d.append(sum(durations[a:b]))
    return out_f, out_d


def sheet_layout(n, fw, fh):
    best = None
    for cols in range(1, n + 1):
        rows = math.ceil(n / cols)
        tw, th = next_pow2(cols * fw), next_pow2(rows * fh)
        if tw > SA_MAX_SHEET or th > SA_MAX_SHEET:
            continue
        score = (tw * th, abs(tw - th))
        if best is None or score < best[0]:
            best = (score, cols, rows, tw, th)
    return best


def process_sa_image(src, dest):
    frames, durations = load_frames(src)
    frames, durations = decimate(frames, durations)
    w, h = frames[0].size
    scale = 2 if h < SA_UPSCALE_BELOW and w * 2 <= 512 else 1
    if scale != 1:
        frames = [f.resize((w * scale, h * scale), Image.NEAREST) for f in frames]
    fw, fh = frames[0].size

    layout = sheet_layout(len(frames), fw, fh)
    while layout is None:
        # Huge animation: shrink until it fits the sheet limit.
        fw, fh = max(1, fw * 3 // 4), max(1, fh * 3 // 4)
        frames = [f.resize((fw, fh), Image.LANCZOS) for f in frames]
        layout = sheet_layout(len(frames), fw, fh)
    _, cols, rows, tw, th = layout

    sheet = Image.new("RGBA", (tw, th), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        sheet.paste(f, ((i % cols) * fw, (i // cols) * fh))
    sheet.save(dest, optimize=True)
    return {"w": w, "h": h, "fw": fw, "fh": fh, "tw": tw, "th": th,
            "n": len(frames), "cols": cols, "d": durations}


def build_sa():
    entries = parse_sa_manifest()
    meta_path = os.path.join(CACHE, "sa_meta.json")
    titles = json.load(open(meta_path, encoding="utf-8")) if os.path.exists(meta_path) else {}

    shutil.rmtree(ICONS_SA, ignore_errors=True)
    os.makedirs(ICONS_SA)

    # Real :codes: always beat the fallback names given to bare emoticons like ;)
    real_codes = {sa_shortcode(e["code"]) for e in entries} - {None}

    used_keys = set()
    items = []
    shortcodes_to_key = OrderedDict()
    emoticons = OrderedDict()
    for e in entries:
        code = e["code"]
        sc = sa_shortcode(code)
        stem = os.path.splitext(os.path.basename(e["file"]))[0]
        stem = re.sub(r"\.\d{3}$", "", re.sub(r"^emot-", "", stem))
        base = "sa_" + slug(sc or stem)
        key = base
        i = 2
        while key in used_keys:
            key = f"{base}_{i}"
            i += 1
        used_keys.add(key)

        src = os.path.join(CACHE, e["file"])
        if not os.path.exists(src):
            print(f"  SA: missing image for {code}: {e['file']}")
            continue
        info = process_sa_image(src, os.path.join(ICONS_SA, key[3:] + ".png"))
        info["file"] = key[3:] + ".png"

        shortcodes = []
        if sc:
            shortcodes.append(sc)
        else:
            emoticons[code] = key
            # Bare emoticons also get a :name: form so the keyboard has something to insert.
            alt = slug(stem)
            if e["file"].startswith("sa_extra/"):
                alt = alt.rsplit("_", 1)[-1]   # downloaded files carry their URL path
            if alt not in shortcodes_to_key and alt not in real_codes:
                shortcodes.append(alt)
        for s in shortcodes:
            if s in shortcodes_to_key:
                print(f"  SA: duplicate shortcode :{s}: ({code}) ignored")
                continue
            shortcodes_to_key[s] = key

        title = titles.get(code, {}).get("title", "")
        words = []
        for wd in re.findall(r"[a-z0-9']+", title.lower()):
            if len(wd) > 2 and wd not in SA_STOPWORDS and wd not in words:
                words.append(wd)
        items.append({"key": key, "code": code, "category": e["category"], "info": info,
                      "shortcodes": [s for s in shortcodes if shortcodes_to_key.get(s) == key],
                      "keywords": words, "emoticon": None if sc else code})

    write_sa_pack_lua(items, shortcodes_to_key, emoticons)
    return items, shortcodes_to_key, emoticons


def write_sa_pack_lua(items, shortcodes_to_key, emoticons):
    groups = OrderedDict()
    for it in items:
        groups.setdefault(it["category"], []).append(it["key"])
    icon_key = next((it["key"] for it in items if it["code"] == ":v:"), items[0]["key"] if items else None)

    out = []
    w = out.append
    w("-- Generated by tools/build.py from tools/sa_manifest.txt. Do not edit.\n")
    w("-- Smileys (c) their respective SomethingAwful forums creators.\n")
    w("local addonName, addon = ...\n\nlocal pack = {\n")
    w(f'\tID = "SomethingAwful",\n\tName = "Something Awful",\n\tIconDir = "{ADDON_PATH}SA\\\\",\n')
    w(f"\tIconKey = {lua_str(icon_key or '')},\n\n")

    w("\t-- file, w/h = source size, fw/fh = frame size in the texture, tw/th = texture size,\n")
    w("\t-- n = frames, cols = frames per sheet row, d = per-frame durations (ms)\n")
    w("\tIcons = {\n")
    for it in items:
        i = it["info"]
        d = ""
        if i["n"] > 1:
            ds = i["d"]
            d = f", d = {ds[0]}" if len(set(ds)) == 1 else f", d = {{ {', '.join(map(str, ds))} }}"
        w(f"\t\t[{lua_str(it['key'])}] = {{ file = {lua_str(i['file'])}, w = {i['w']}, h = {i['h']}, "
          f"fw = {i['fw']}, fh = {i['fh']}, tw = {i['tw']}, th = {i['th']}, n = {i['n']}, cols = {i['cols']}{d} }},\n")
    w("\t},\n\n")

    total = len(items)
    w(f"\tGroupInfo = {{\n\t\tGroupCount = {len(groups)},\n\t\tEmojiCount = {total},\n")
    for gname, keys in groups.items():
        w(f"\t\t{{\n\t\t\tName = {lua_str(gname)},\n\t\t\tIconKey = {lua_str(keys[0])},\n"
          f"\t\t\tSubGroupCount = 1,\n\t\t\tEmojiCount = {len(keys)},\n")
        w(f"\t\t\t{{\n\t\t\t\tName = {lua_str(gname)},\n\t\t\t\tEmojiCount = {len(keys)},\n")
        w(lua_list(keys, 4))
        w("\t\t\t},\n\t\t},\n")
    w("\t},\n\n")

    w("\tShortcodesToKey = {\n")
    for sc, key in shortcodes_to_key.items():
        w(f"\t\t[{lua_str(sc)}] = {lua_str(key)},\n")
    w("\t},\n\tShortcodeList = {\n")
    w(lua_list(list(shortcodes_to_key), 2))
    w(f"\t\tShortcodeCount = {len(shortcodes_to_key)},\n\t}},\n\n")

    w("\t-- Bare text smileys like :) that are matched outside :colons:\n\tEmoticons = {\n")
    for text, key in emoticons.items():
        w(f"\t\t[{lua_str(text)}] = {lua_str(key)},\n")
    w("\t},\n\n")

    kw_index = OrderedDict()
    for it in items:
        for kw in it["keywords"]:
            kw_index.setdefault(kw, []).append(it["key"])
    w("\tKeywordList = {\n")
    w(lua_list(list(kw_index), 2))
    w(f"\t\tKeywordCount = {len(kw_index)},\n")
    w("\t},\n\tKeywordIndexes = {\n")
    for kw, keys in kw_index.items():
        w(f"\t\t[{lua_str(kw)}] = {{ {', '.join(lua_str(k) for k in keys)} }},\n")
    w("\t},\n\n")

    for it in items:
        w(f"\t[{lua_str(it['key'])}] = {{\n\t\tName = {lua_str(it['code'])},\n")
        w(f"\t\tShortcodes = {{ {', '.join(lua_str(s) for s in it['shortcodes'])} }},\n")
        if it["emoticon"]:
            w(f"\t\tEmoticon = {lua_str(it['emoticon'])},\n")
        if it["keywords"]:
            w(f"\t\tKeywords = {{ {', '.join(lua_str(k) for k in it['keywords'])} }},\n")
        w("\t},\n")
    w("}\n\naddon:RegisterStickerPack(pack)\n")

    with open(os.path.join(DATA, "SAPack.lua"), "w", encoding="utf-8") as f:
        f.write("".join(out))


